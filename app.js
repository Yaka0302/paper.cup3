let selected = "rabbit";
let playMode = "normal";
let stream = null;
let guideTimer = null;
let faceMesh = null;
let faceLoopRunning = false;
let lastFaceSend = 0;
let currentMusicMode = "calm";

let audioContext = null;
let masterGain = null;
let musicTimer = null;
let musicStep = 0;

const $ = id => document.getElementById(id);

function drawButtons() {
  const root = $("craftGrid");
  root.innerHTML = "";

  Object.entries(crafts).forEach(([key, craft]) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "craft" + (key === selected ? " selected" : "");
    button.innerHTML = `<span>${craft.emoji}</span>${craft.name}`;

    button.addEventListener("click", () => {
      selected = key;
      stopOrgel();
      drawButtons();
      showCraft();
    });

    root.appendChild(button);
  });
}

function showCraft() {
  const craft = crafts[selected];

  $("craftTitle").textContent = `${craft.emoji} ${craft.name}の つくりかた`;
  $("finishedPhoto").src = craft.image;
  $("finishedPhoto").alt = `${craft.name}の できあがりしゃしん`;
  $("steps").innerHTML = craft.steps.map(step => `<li>${step}</li>`).join("");
  $("pdfLink").href = craft.pdf;
  $("pdfLink").setAttribute("download", craft.pdf);
  $("cameraTitle").textContent = `${craft.emoji} ${craft.name}を もってね`;
}

function ensureAudio() {
  if (!audioContext) {
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (!AudioContextClass) return false;

    audioContext = new AudioContextClass();

    masterGain = audioContext.createGain();
    masterGain.gain.value = playMode === "care" ? 0.09 : 0.16;

    const lowPass = audioContext.createBiquadFilter();
    lowPass.type = "lowpass";
    lowPass.frequency.value = 1450;
    lowPass.Q.value = 0.3;

    masterGain.connect(lowPass);
    lowPass.connect(audioContext.destination);
  }

  if (audioContext.state === "suspended") {
    audioContext.resume().catch(() => {});
  }

  return true;
}

function playOrgelNote(noteName, beatSeconds) {
  if (!audioContext || !masterGain) return;

  const frequency = NOTE_HZ[noteName] || 0;
  if (!frequency) return;

  const now = audioContext.currentTime;
  const oscillator = audioContext.createOscillator();
  const gain = audioContext.createGain();

  oscillator.type = "sine";
  oscillator.frequency.setValueAtTime(frequency, now);

  gain.gain.setValueAtTime(0.0001, now);
  gain.gain.exponentialRampToValueAtTime(0.09, now + 0.04);
  gain.gain.exponentialRampToValueAtTime(
    0.0001,
    now + Math.max(0.5, beatSeconds * 0.88)
  );

  oscillator.connect(gain);
  gain.connect(masterGain);

  oscillator.start(now);
  oscillator.stop(now + Math.max(0.55, beatSeconds));
}

function updateMusicLabel(expression) {
  const labels = {
    bright: "🎵 あかるい オルゴール",
    calm: "🎵 ゆっくり オルゴール",
    wonder: "🎵 わくわく オルゴール"
  };

  if ($("musicState")) {
    $("musicState").textContent = labels[expression] || labels.calm;
  }
}

function startOrgel(expression = "calm", restart = false) {
  if (!ensureAudio()) {
    if ($("musicState")) {
      $("musicState").textContent = "🔊 この ぶらうざでは おとを つかえません";
    }
    return;
  }

  currentMusicMode = expression;
  if (masterGain) {
    masterGain.gain.value = playMode === "care" ? 0.09 : 0.16;
  }
  updateMusicLabel(expression);

  if (restart) musicStep = 0;

  if (musicTimer) {
    clearTimeout(musicTimer);
    musicTimer = null;
  }

  const tick = () => {
    const melody = ORGEL[selected][currentMusicMode] || ORGEL[selected].calm;
    const beatSeconds = 60 / melody.bpm;
    const note = melody.notes[musicStep % melody.notes.length];

    playOrgelNote(note, beatSeconds);

    musicStep += 1;
    musicTimer = setTimeout(tick, beatSeconds * 1000);
  };

  tick();
}

function stopOrgel() {
  if (musicTimer) {
    clearTimeout(musicTimer);
    musicTimer = null;
  }
}

function setMusicMode(mode) {
  const expression =
    mode === "bright" ? "bright" :
    mode === "wonder" ? "wonder" :
    "calm";

  if (expression === currentMusicMode && musicTimer) return;
  startOrgel(expression, false);
}

function distance(a, b) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}

function handleFaceResults(results) {
  const landmarks = results.multiFaceLandmarks?.[0];

  if (!landmarks) {
    setMusicMode("calm");
    return;
  }

  const faceWidth = distance(landmarks[234], landmarks[454]) || 1;
  const mouthWidth = distance(landmarks[61], landmarks[291]) / faceWidth;
  const mouthOpen = distance(landmarks[13], landmarks[14]) / faceWidth;
  const cornerY = (landmarks[61].y + landmarks[291].y) / 2;
  const mouthCenterY = (landmarks[13].y + landmarks[14].y) / 2;
  const smileLift = mouthCenterY - cornerY;

  if (mouthOpen > 0.050) {
    setMusicMode("wonder");
  } else if (mouthWidth > 0.35 && smileLift > 0.003) {
    setMusicMode("bright");
  } else {
    setMusicMode("calm");
  }
}

async function setupFaceMesh() {
  if (faceMesh || typeof FaceMesh === "undefined") return;

  faceMesh = new FaceMesh({
    locateFile: file =>
      `https://cdn.jsdelivr.net/npm/@mediapipe/face_mesh/${file}`
  });

  faceMesh.setOptions({
    maxNumFaces: 1,
    refineLandmarks: true,
    minDetectionConfidence: 0.5,
    minTrackingConfidence: 0.5
  });

  faceMesh.onResults(handleFaceResults);
  await faceMesh.initialize();
}

async function faceLoop(timestamp) {
  if (!faceLoopRunning) return;

  const video = $("video");

  if (
    faceMesh &&
    video &&
    video.readyState >= 2 &&
    timestamp - lastFaceSend > 180
  ) {
    lastFaceSend = timestamp;

    try {
      await faceMesh.send({ image: video });
    } catch (error) {
      console.warn("表情認識を一時的にスキップしました。", error);
    }
  }

  requestAnimationFrame(faceLoop);
}

function startGuide() {
  const sequence = crafts[selected].missions;
  let index = 0;

  $("guide").textContent = sequence[0];
  clearInterval(guideTimer);

  guideTimer = setInterval(() => {
    index += 1;

    if (index < sequence.length) {
      $("guide").textContent = sequence[index];
    } else {
      clearInterval(guideTimer);
      $("guide").textContent =
        "🎉 いっぱい あそべたね！ また あそぼうね！";
    }
  }, playMode === "care" ? 11000 : 8000);
}

async function startMusicFromButton() {
  if (!ensureAudio()) return;

  try {
    await audioContext.resume();
  } catch (error) {
    console.warn("おとの じゅんびに しっぱいしました。", error);
  }

  musicStep = 0;
  currentMusicMode = "calm";
  startOrgel("calm", true);
}

async function openCameraAndPlay() {
  $("cameraPanel").classList.add("open");
  $("cameraPanel").scrollIntoView({ behavior: "smooth", block: "start" });

  await startMusicFromButton();
  startGuide();

  try {
    stream = await navigator.mediaDevices.getUserMedia({
      video: { facingMode: "user" },
      audio: false
    });

    $("video").srcObject = stream;
    await $("video").play();

    try {
      await setupFaceMesh();

      if (faceMesh) {
        faceLoopRunning = true;
        requestAnimationFrame(faceLoop);
      }
    } catch (error) {
      console.warn("表情認識を利用できません。", error);
      $("musicState").textContent = "🎵 ゆっくり オルゴール";
    }
  } catch (error) {
    $("guide").textContent =
      "かめらを つかえません。おんがくだけでも あそべるよ！";
  }
}

function closeCamera() {
  clearInterval(guideTimer);
  faceLoopRunning = false;
  stopOrgel();

  if (stream) {
    stream.getTracks().forEach(track => track.stop());
  }

  stream = null;
  $("video").srcObject = null;
  $("cameraPanel").classList.remove("open");
  $("nextBtn").scrollIntoView({ behavior: "smooth", block: "center" });
}


function setPlayMode(mode) {
  playMode = mode === "care" ? "care" : "normal";
  document.body.classList.toggle("care-mode", playMode === "care");

  const normalButton = $("normalModeBtn");
  const careButton = $("careModeBtn");

  if (normalButton) {
    normalButton.classList.toggle("selected", playMode === "normal");
  }
  if (careButton) {
    careButton.classList.toggle("selected", playMode === "care");
  }

  if (masterGain) {
    masterGain.gain.value = playMode === "care" ? 0.09 : 0.16;
  }

  if ($("musicState")) {
    $("musicState").textContent =
      playMode === "care"
        ? "🌿 はいりょばん：ちいさな おと・ゆっくり"
        : "🌈 つうじょうばん：ふつうの おと・はやさ";
  }
}

if ($("normalModeBtn")) {
  $("normalModeBtn").addEventListener("click", () => setPlayMode("normal"));
}
if ($("careModeBtn")) {
  $("careModeBtn").addEventListener("click", () => setPlayMode("care"));
}

$("nextBtn").addEventListener("click", openCameraAndPlay);

$("replayBtn").addEventListener("click", async () => {
  stopOrgel();
  await startMusicFromButton();
  startGuide();
});

$("closeBtn").addEventListener("click", closeCamera);

setPlayMode("normal");
drawButtons();
showCraft();
